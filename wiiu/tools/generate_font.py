#!/usr/bin/env python3
"""Bake OFL-licensed upstream Nunito font outlines into native C glyph alpha maps.

This reproduces the UI typography without using a font engine at runtime.
Font sources are assets/fonts/Nunito-{Regular,Bold,ExtraBold}.ttf in upstream.
The generated C is a build intermediate, NOT copied font files or fonts
for redistribution. Pillow (PIL) is required at build time.
"""
import argparse
from pathlib import Path
from PIL import ImageFont

SIZES = (
    ("Regular", 13), ("Bold", 16), ("ExtraBold", 25),
    ("Regular", 16), ("Bold", 21), ("ExtraBold", 33),
)
# Latin-1 and all punctuation used by the canonical descriptions/UI.
CHARS = sorted(set(range(32, 256)) | {
    0x0153, 0x0160, 0x0161, 0x0178, 0x0192, 0x02c6,
    0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d,
    0x2022, 0x2026, 0x2039, 0x203a, 0x20ac,
    0x2122, 0x2605, 0x2606,
})


def build(font_dir):
    faces = []
    data = bytearray()
    for weight, size in SIZES:
        font = ImageFont.truetype(str(font_dir / f"Nunito-{weight}.ttf"), size)
        glyphs = []
        for point in CHARS:
            letter = chr(point)
            mask, (left, top) = font.getmask2(letter, mode="L", anchor="lt")
            width, height = mask.size
            if width > 80 or height > 80:
                raise ValueError("unexpected oversized glyph")
            advance = round(font.getlength(letter))
            offset = len(data)
            data.extend(bytes(mask))
            glyphs.append((point, offset, width, height, left, top, advance))
        faces.append((weight, size, glyphs))
    return faces, data


def emit(out, faces, pixels):
    parts = [
        "/* AUTOGENERATED: upstream Nunito / SIL Open Font License 1.1. */",
        '#include "font_nunito.h"',
        "#include <stddef.h>",
        "",
    ]
    for index, (weight, size, glyphs) in enumerate(faces):
        parts += [f"static const NunitoGlyph face_{index}[] = {{"]
        for point, offset, width, height, left, top, advance in glyphs:
            parts.append(f"  {{{point}, {offset}, {width}, {height}, {left}, {top}, {advance}}},")
        parts.append("};")
    parts.append("const uint8_t nunito_pixels[] = {")
    for index in range(0, len(pixels), 28):
        parts.append("  " + ", ".join(str(v) for v in pixels[index:index + 28]) + ",")
    parts += [
        "};",
        "const NunitoFace nunito_faces[] = {",
    ]
    for i, (weight, size, glyphs) in enumerate(faces):
        parts.append(f"  {{face_{i}, {len(glyphs)}, {size}}},")
    parts += [
        "};",
        f"const size_t nunito_pixels_size = {len(pixels)};",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="utf-8")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    faces, pixels = build(args.root / "assets/fonts")
    emit(args.output, faces, pixels)
    print(f"Nunito: {len(faces)} font faces, {len(CHARS)} glyphs each; {len(pixels)} alpha bytes.")


if __name__ == "__main__":
    main()
